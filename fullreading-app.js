(function () {
  const TEMPLATE_HEADER = `你現在是一位誠實、客觀、理性且熟悉傳統牌義的塔羅師／神諭卡解讀者。
你的任務不是安慰我、討好我、給我希望，也不是刻意製造負面結果，而是忠實依照牌面本身的象徵、正逆位、牌陣位置，以及不同牌組之間的關聯進行解讀。
請把塔羅視為一種象徵性、自我探索與情境分析工具，而不是絕對預言。
不要把牌義當成醫學、心理診斷、法律、財務或其他專業事實；涉及這些領域時，要清楚區分「牌面象徵」與「現實世界可以驗證的事實」。
一、基本解讀原則
請遵守以下原則：
1. 誠實，不討好
不要因為某張牌不好聽，就刻意美化。
如果牌面顯示：

* 逃避
* 自欺
* 執著
* 控制
* 恐懼
* 依賴
* 權力失衡
* 欲望
* 消耗
* 失敗
* 延遲
* 不切實際
* 重複錯誤
* 關係問題

就直接說明。
同樣地，如果牌面真的有：

* 機會
* 成長
* 支持
* 突破
* 成功
* 穩定
* 修復
* 新開始

也要如實指出。
不要為了讓答案好聽而把負面牌解成正面。
2. 正面與反面都必須描述
每張牌都請同時回答：

* 這張牌的正面／有利面是什麼？
* 這張牌的負面／陰影面是什麼？
* 在目前問題裡，它比較偏向哪一面？
* 為什麼？

不要只列出牌義，要結合問題與牌陣位置。
3. 不要過度心理化
不要看到「寶劍九」就直接斷言我有焦慮症。
不要看到「惡魔」就直接斷言我有成癮。
不要看到「塔」就直接說一定會發生災難。
請使用：
「可能代表……」
「牌面比較像……」
「如果這張牌對應到你的情況，可能表現為……」
並清楚區分：
牌面象徵 ≠ 客觀事實 ≠ 醫學／心理診斷。
4. 不要硬湊牌義
如果不同牌之間沒有明顯關聯，不要為了製造故事而強行串聯。
如果牌面互相矛盾，請直接指出：
「這裡存在矛盾訊息。」
並分析可能原因。
例如：

* 一張牌代表前進，另一張代表停滯
* 一張牌代表信任，另一張代表懷疑
* 一張牌代表結束，另一張代表抗拒結束

不要把矛盾消掉。
5. 不要把所有牌都解讀成「創傷」
除非牌面與問題真的有充分關聯，否則不要任意套用：

* 童年創傷
* 依附問題
* 原生家庭
* 潛意識創傷
* 人格問題

如果有這些訊息，請說明「牌面可能呈現的模式」，而不是直接下診斷。
二、第一部分：先完整解讀塔羅
如果提供的是凱爾特十字或其他牌陣，請按照牌陣位置逐張解讀。
每張牌請使用以下格式：
【位置｜牌名｜正／逆位】
核心牌義：
說明這張牌在傳統塔羅中的基本象徵。
正面訊息：
這張牌可以帶來什麼資源、機會或正向可能。
反面／陰影訊息：
這張牌可能代表什麼問題、盲點、阻礙或不成熟的表現。
放在這個位置代表：
針對牌陣位置與我的問題進行具體解讀。
較可能的方向：
說明目前比較偏向正面還是負面，並解釋原因。
三、第二部分：解讀四組神諭卡
四組神諭卡請分別處理，不要一開始就全部混在一起。
每一組都先回答：
這一組牌在整體故事中的功能是什麼？
例如可能是：

* 根本原因
* 童年／過去模式
* 當前心理狀態
* 防衛機制
* 行動指引
* 未來方向
* 修復方式

但不要預設一定是哪一種，要依照牌組名稱與實際內容判斷。
四組牌的每一張都要分析：
【牌名】
核心牌義：
正面面向：
負面／陰影面：
如果過度發展，會變成什麼？
如果正確運用，可以成為什麼力量？
與塔羅的對應：
指出它是否與塔羅中的某張牌、某個主題形成呼應。
如果沒有明顯對應，就直接說沒有必要硬連。
四、四組牌之間進行交叉分析
完成單張牌解讀後，再把：
塔羅＋神諭卡第一組＋神諭卡第二組＋神諭卡第三組＋神諭卡第四組
放在一起分析。
請找出：
A. 重複出現的主題
例如：

* 控制
* 恐懼
* 關係
* 自我價值
* 安全感
* 逃避
* 行動
* 信任
* 結束
* 重生

但不要預設主題，必須由牌面實際歸納。
B. 相互支持的牌
指出哪些牌正在講相同的事情。
例如：
「寶劍八＋某神諭卡」都指向限制感。
請說明為什麼。
C. 相互矛盾的牌
如果有矛盾，一定要指出。
例如：
「塔羅顯示想前進，但神諭卡顯示抗拒改變。」
請解釋：

* 可能代表內在拉扯
* 不同時間尺度
* 外在與內在不一致
* 意識與潛意識不同
* 或單純代表兩種不同可能

不要強行說它們其實完全一致。
D. 最重要的牌
請選出整個牌組中最關鍵的 3～5 張牌。
並說明：
為什麼是它們，而不是其他牌？
五、區分「牌面訊息」與「我的投射」
這一段非常重要。
請明確區分：
牌面比較直接支持的訊息
哪些是多張牌反覆呈現、可信度相對較高的主題。
可能只是我的投射
哪些解讀比較依賴假設，需要我自己驗證。
目前無法從牌面判斷的事情
不要因為我很想知道，就硬給答案。
如果牌面不足以回答，請直接說：
「這部分牌面沒有足夠資訊。」
六、如果問題涉及「原因」
不要只給一個原因。
請區分：
表層原因
目前最直接看到的問題。
中層原因
行為模式、思考方式、關係模式等。
深層原因
牌面如果真的支持，再討論更深層的心理／情緒模式。
並告訴我：
哪一層是牌面證據最強的？
不要把最深層的解讀自動當成真正原因。
七、如果問題涉及未來
不要說：
「一定會發生。」
請使用概率式、條件式語言。
例如：
「目前牌面比較偏向 A，但如果維持目前模式，B 的可能性會增加。」
或：
「這張牌本身不是必然事件，而比較像一個需要注意的趨勢。」
同時告訴我：
如果維持目前模式
最可能發展什麼？
如果改變目前模式
可能出現什麼不同結果？
八、最後一定要給「正面結論」與「反面結論」
不要只給一個漂亮的總結。
請分成：
最有利的可能性
牌面中真正存在的機會與資源。
最需要警惕的可能性
牌面中最明顯的盲點與風險。
最可能的中間路徑
如果不過度悲觀，也不過度樂觀，目前最合理的判斷是什麼。
九、最後給出真正可執行的建議
最多列出 3～5 件事。
每件事情都必須能對應到牌面。
不要給空泛的：
「相信自己」
「保持正能量」
「勇敢做自己」
除非你能解釋它具體要怎麼做。
建議最好寫成：
「牌面指出 X，因此現實中可以嘗試 Y。」
例如：
「因為寶劍八與某牌都呈現過度限制，所以與其增加規則，更適合先減少一條不必要的規則。」
十、最後的總結格式
請最後用以下結構：
一句話結論
用一句最直接的話回答我的問題。
真正核心
說明整個牌組最深的共同主題。
正面訊息
我目前擁有哪些資源、機會與可能性？
反面訊息
我最容易在哪裡自欺、逃避或重複錯誤？
最大盲點
如果我只看到牌面的正面，最可能漏掉什麼？
最大機會
如果我真的按照牌面調整，最可能突破什麼？
最可能的發展
不要講必然結果，而是描述目前趨勢。
現實行動
給我 3～5 個具體可執行的方向。
最重要的總規則
請始終記住：
你不是來哄我的。
你也不是來嚇我的。
你要做的是：
忠實牌義 → 結合牌陣 → 分析正反兩面 → 找重複主題 → 指出矛盾 → 區分事實與象徵 → 最後給出合理結論。
如果牌很好，就說好。
如果牌不好，就說不好。
如果牌面矛盾，就說矛盾。
如果不知道，就說不知道。
如果只能推測，就標明「這是推測」。
不要為了讓故事完整而補上牌面沒有提供的資訊。
請用清楚、直接、不煽情的語氣回答。
最後不要只告訴我「這副牌想對你說什麼」，也要告訴我：
「如果這副牌的警告是對的，我現實生活中最需要改變的到底是什麼？」`;

  const SPREADS = {
    single: { label: "單張指引", count: 1, positions: ["指引"] },
    three: { label: "過去現在未來", count: 3, positions: ["過去", "現在", "未來"] },
    choice: {
      label: "二擇一",
      count: 5,
      positions: ["現況", "選項 A · 優勢", "選項 A · 挑戰", "選項 B · 優勢", "選項 B · 挑戰"],
    },
    celtic: {
      label: "凱爾特十字",
      count: 10,
      positions: [
        "1 · 現況", "2 · 阻礙／助力", "3 · 深層基礎", "4 · 近期過去", "5 · 可能結果",
        "6 · 近期未來", "7 · 自我態度", "8 · 外在影響", "9 · 希望與恐懼", "10 · 最終結果",
      ],
    },
  };

  const spreadButtons = document.querySelectorAll(".spread-btn");
  const customCountField = document.getElementById("customCountField");
  const customCountInput = document.getElementById("customCount");
  const decreaseBtn = document.getElementById("decreaseBtn");
  const increaseBtn = document.getElementById("increaseBtn");
  const allowReversedCheckbox = document.getElementById("allowReversed");
  const oracleButtons = document.querySelectorAll(".draw-btn");
  const questionInput = document.getElementById("questionInput");

  const drawBtn = document.getElementById("drawBtn");
  const resetBtn = document.getElementById("resetBtn");

  const deckStatus = document.getElementById("deckStatus");
  const statusText = document.getElementById("statusText");
  const reading = document.getElementById("reading");

  const tarotSub = document.getElementById("tarotSub");
  const tarotList = document.getElementById("tarotList");
  const childList = document.getElementById("childList");
  const studioList = document.getElementById("studioList");
  const pantheonList = document.getElementById("pantheonList");
  const angelList = document.getElementById("angelList");

  const resultText = document.getElementById("resultText");
  const copyTextBtn = document.getElementById("copyTextBtn");

  const MAX_CUSTOM_CARDS = FULL_DECK.length - 1;
  let selectedSpreadKey = "three";
  let selectedOracleCount = 1;

  function clampCustomCount(value) {
    let n = parseInt(value, 10);
    if (isNaN(n)) n = 1;
    return Math.min(Math.max(n, 1), MAX_CUSTOM_CARDS);
  }

  function getSpread(key) {
    if (key === "custom") {
      const count = clampCustomCount(customCountInput.value);
      return {
        label: "自訂牌陣",
        count,
        positions: Array.from({ length: count }, (_, i) => `第 ${i + 1} 張`),
      };
    }
    return SPREADS[key];
  }

  spreadButtons.forEach((btn) => {
    btn.addEventListener("click", () => {
      selectedSpreadKey = btn.dataset.key;
      spreadButtons.forEach((b) => b.classList.toggle("active", b === btn));
      customCountField.hidden = selectedSpreadKey !== "custom";
    });
  });

  customCountInput.addEventListener("change", () => {
    customCountInput.value = clampCustomCount(customCountInput.value);
  });

  decreaseBtn.addEventListener("click", () => {
    customCountInput.value = clampCustomCount(Number(customCountInput.value) - 1);
  });

  increaseBtn.addEventListener("click", () => {
    customCountInput.value = clampCustomCount(Number(customCountInput.value) + 1);
  });

  oracleButtons.forEach((btn) => {
    btn.addEventListener("click", () => {
      selectedOracleCount = Number(btn.dataset.count);
      oracleButtons.forEach((b) => b.classList.toggle("active", b === btn));
    });
  });

  function shuffleArray(array) {
    const arr = array.slice();
    for (let i = arr.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [arr[i], arr[j]] = [arr[j], arr[i]];
    }
    return arr;
  }

  function drawTarot(spread, allowReversed) {
    const shuffled = shuffleArray(FULL_DECK);
    return shuffled.slice(0, spread.count).map((card) => ({
      card,
      reversed: allowReversed ? Math.random() < 0.5 : false,
    }));
  }

  function drawOracle(deck, count) {
    return shuffleArray(deck).slice(0, count);
  }

  function renderTarot(spread, entries) {
    tarotSub.textContent = `${spread.label} 牌陣`;
    tarotList.innerHTML = "";
    entries.forEach((entry, i) => {
      const line = document.createElement("div");
      line.className = "card-line";
      line.innerHTML = `
        <span class="card-pos">${spread.positions[i]}</span>
        <span class="card-name">${entry.card.name}</span>
        <span class="card-en">${entry.card.en}</span>
        <span class="orientation-badge ${entry.reversed ? "reversed" : "upright"}">${entry.reversed ? "逆位" : "正位"}</span>
      `;
      tarotList.appendChild(line);
    });
  }

  function renderOracle(listEl, cards) {
    listEl.innerHTML = "";
    cards.forEach((card, i) => {
      const line = document.createElement("div");
      line.className = "card-line";
      line.innerHTML = `
        <span class="card-pos">${i + 1}</span>
        <span class="card-name">${card.name}</span>
        <span class="card-en">${card.en}</span>
      `;
      listEl.appendChild(line);
    });
  }

  function tarotBlockText(spread, entries) {
    const lines = [`${spread.label} 牌陣`];
    entries.forEach((entry, i) => {
      lines.push(`${spread.positions[i]}：${entry.card.name}（${entry.reversed ? "逆位" : "正位"}）`);
    });
    return lines.join("\n");
  }

  function oracleBlockText(deckLabel, cards, renderCard) {
    const lines = [deckLabel];
    cards.forEach((card, i) => {
      lines.push(renderCard(card, i + 1));
    });
    return lines.join("\n");
  }

  function renderChildCard(card, i) {
    return `${i}. ${card.name}｜${card.en}\n   本質：${card.essence}\n   療癒句：${card.heal}`;
  }

  function renderStudioCard(card, i) {
    return `${i}. ${card.name}｜${card.en}\n   慣性成因：${card.cause}\n   轉念台詞：${card.line}`;
  }

  function renderPantheonCard(card, i) {
    return `${i}. ${card.name}｜${card.en}（${card.epithet}）\n   神諭：${card.voice}`;
  }

  function renderAngelCard(card, i) {
    return `${i}. ${card.name}｜${card.en}\n   指引：${card.guidance}`;
  }

  function buildFullText(spread, tarotEntries, childCards, studioCards, pantheonCards, angelCards) {
    const question = questionInput.value.trim() || "（尚未填寫，請在上方輸入你的問題）";

    return [
      TEMPLATE_HEADER,
      "",
      "我的問題：",
      question,
      "",
      "塔羅牌：",
      tarotBlockText(spread, tarotEntries),
      "",
      "神諭卡第一組：",
      oracleBlockText("童年碎片拾光卡", childCards, renderChildCard),
      "",
      "神諭卡第二組：",
      oracleBlockText("內在片場神諭卡", studioCards, renderStudioCard),
      "",
      "神諭卡第三組：",
      oracleBlockText("萬神歸途指引卡", pantheonCards, renderPantheonCard),
      "",
      "神諭卡第四組：",
      oracleBlockText("天使落地指引卡", angelCards, renderAngelCard),
      "",
      "請開始完整分析。",
    ].join("\n");
  }

  drawBtn.addEventListener("click", () => {
    const spread = getSpread(selectedSpreadKey);
    const allowReversed = allowReversedCheckbox.checked;

    drawBtn.disabled = true;
    reading.hidden = true;
    deckStatus.hidden = false;
    statusText.textContent = "洗牌中…";

    setTimeout(() => {
      statusText.textContent = "正在抽牌…";

      const tarotEntries = drawTarot(spread, allowReversed);
      const childCards = drawOracle(CHILD_DECK, selectedOracleCount);
      const studioCards = drawOracle(STUDIO_DECK, selectedOracleCount);
      const pantheonCards = drawOracle(PANTHEON_DECK, selectedOracleCount);
      const angelCards = drawOracle(ANGEL_DECK, selectedOracleCount);

      setTimeout(() => {
        deckStatus.hidden = true;
        drawBtn.disabled = false;
        resetBtn.disabled = false;

        renderTarot(spread, tarotEntries);
        renderOracle(childList, childCards);
        renderOracle(studioList, studioCards);
        renderOracle(pantheonList, pantheonCards);
        renderOracle(angelList, angelCards);

        resultText.value = buildFullText(spread, tarotEntries, childCards, studioCards, pantheonCards, angelCards);
        copyTextBtn.textContent = "📋 複製文字";

        reading.hidden = false;
      }, 500);
    }, 900);
  });

  resetBtn.addEventListener("click", () => {
    reading.hidden = true;
    resultText.value = "";
    resetBtn.disabled = true;
  });

  copyTextBtn.addEventListener("click", () => {
    const text = resultText.value;

    const showCopied = () => {
      copyTextBtn.textContent = "✅ 已複製";
      setTimeout(() => {
        copyTextBtn.textContent = "📋 複製文字";
      }, 1500);
    };

    if (navigator.clipboard && navigator.clipboard.writeText) {
      navigator.clipboard.writeText(text).then(showCopied).catch(() => {
        resultText.select();
        document.execCommand("copy");
        showCopied();
      });
    } else {
      resultText.select();
      document.execCommand("copy");
      showCopied();
    }
  });
})();
